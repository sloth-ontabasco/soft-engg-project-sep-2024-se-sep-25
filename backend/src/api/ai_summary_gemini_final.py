class ResponseFormatter(BaseModel): # Add mandatory check name to all the fields
    answer: str = Field(description="The complete response that was generated by the model")
    summary: str = Field(description="A high level summary of the submission")
    team: str = Field(description="The team that submitted the project") # pull this directly from the APIs
    completed: str = Field(description="The tasks that were completed by the team in HTML compatible list format")
    not_or_partially_completed: str = Field(description="The tasks that were not or partially completed by the team in HTML compatible list format")
    suggestions: str = Field(description="Suggestions for improvement (if any) in HTML compatible list format")
    rubrix_provided: bool = Field(description="Whether a rubrix was provided")
    grade: str = Field(description="The grade of the submission") #convert the rubrix evaluation to a % and then into a grade


